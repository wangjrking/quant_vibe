def _to_float(value, default=None):
    try:
        value = float(value)
    except (TypeError, ValueError):
        return default
    if math.isnan(value) or math.isinf(value):
        return default
    return value


def _load_fusion_features() -> dict[tuple[str, str], dict]:
    conn = sqlite3.connect(FUSION_DB)
    conn.row_factory = sqlite3.Row
    rows = conn.execute(
        """
        SELECT trade_date, stock_code, pred_10d, pred_5d, amount, turnover_rate,
               total_mv, atr_qfq, close, rank_5d, rank_10d
        FROM fusion_rank_base
        """
    ).fetchall()
    conn.close()
    features = {}
    for row in rows:
        close_price = _to_float(row["close"])
        atr = _to_float(row["atr_qfq"])
        pred_5d = _to_float(row["pred_5d"])
        pred_10d = _to_float(row["pred_10d"])
        features[(str(row["trade_date"]), str(row["stock_code"]))] = {
            "pred_5d": pred_5d,
            "pred_10d": pred_10d,
            "amount": _to_float(row["amount"]),
            "turnover_rate": _to_float(row["turnover_rate"]),
            "total_mv": _to_float(row["total_mv"]),
            "atr_ratio": atr / close_price if atr is not None and close_price and close_price > 0 else None,
            "rank_5d": _to_float(row["rank_5d"]),
            "rank_10d": _to_float(row["rank_10d"]),
            "abs_pred_gap": abs(pred_5d - pred_10d) if pred_5d is not None and pred_10d is not None else None,
        }
    return features


def _load_base_rows() -> list[dict]:
    with BASE_SIGNAL.open("r", encoding="utf-8-sig", newline="") as file:
        return list(csv.DictReader(file))


def _signal_features(rows: list[dict]) -> dict[str, dict]:
    grouped: dict[str, list[dict]] = {}
    for row in rows:
        grouped.setdefault(str(row.get("signal_date") or ""), []).append(row)
    features = {}
    for signal_date, items in grouped.items():
        preds = [_to_float(row.get("pred_prob"), 0.0) or 0.0 for row in items]
        features[signal_date] = {
            "primary_count": sum(1 for value in preds if value >= 2.0),
            "avg_pred": sum(preds) / len(preds) if preds else None,
        }
    return features


def _passes(row: dict, variant: dict, signal_features: dict, fusion_features: dict) -> bool:
    rank = int(float(row.get("rank") or 999999))
    if rank > int(variant.get("rank_max", 999999)):
        return False
    day_features = signal_features.get(str(row.get("signal_date") or ""), {})
    if int(day_features.get("primary_count") or 0) < int(variant.get("primary_count_min", 0)):
        return False
    key = (str(row.get("signal_date") or ""), str(row.get("stock_code") or ""))
    stock_features = fusion_features.get(key)
    if not stock_features:
        return False
    checks = [
        ("min_amount", "amount", lambda actual, threshold: actual >= threshold),
        ("min_turnover", "turnover_rate", lambda actual, threshold: actual >= threshold),
        ("max_turnover", "turnover_rate", lambda actual, threshold: actual <= threshold),
        ("min_total_mv", "total_mv", lambda actual, threshold: actual >= threshold),
        ("max_total_mv", "total_mv", lambda actual, threshold: actual <= threshold),
        ("max_atr_ratio", "atr_ratio", lambda actual, threshold: actual <= threshold),
        ("min_pred_5d", "pred_5d", lambda actual, threshold: actual >= threshold),
        ("min_pred_10d", "pred_10d", lambda actual, threshold: actual >= threshold),
        ("max_rank_5d", "rank_5d", lambda actual, threshold: actual <= threshold),
        ("max_rank_10d", "rank_10d", lambda actual, threshold: actual <= threshold),
        ("min_rank_5d", "rank_5d", lambda actual, threshold: actual >= threshold),
        ("min_rank_10d", "rank_10d", lambda actual, threshold: actual >= threshold),
        ("max_abs_pred_gap", "abs_pred_gap", lambda actual, threshold: actual <= threshold),
    ]
    for variant_key, feature_key, predicate in checks:
        if variant_key not in variant:
            continue
        actual = stock_features.get(feature_key)
        if actual is None or not predicate(float(actual), float(variant[variant_key])):
            return False
    return True


def _write_variant_signal(variant: dict, signal_file: Path) -> None:
    rows = _load_base_rows()
    signal_features = _signal_features(rows)
    fusion_features = _load_fusion_features()
    fieldnames = list(rows[0].keys()) if rows else []
    passed_rows = []
    passed_by_date: dict[str, list[dict]] = {}
    for row in rows:
        if not _passes(row, variant, signal_features, fusion_features):
            continue
        passed_rows.append(row)
        passed_by_date.setdefault(str(row.get("signal_date") or ""), []).append(row)

    post_filter_day_features = {}
    for signal_date, day_rows in passed_by_date.items():
        preds = [_to_float(row.get("pred_prob"), 0.0) or 0.0 for row in day_rows]
        post_filter_day_features[signal_date] = {
            "count": len(day_rows),
            "primary_count": sum(1 for value in preds if value >= 2.0),
            "avg_pred": sum(preds) / len(preds) if preds else None,
        }

    signal_file.parent.mkdir(parents=True, exist_ok=True)
    with signal_file.open("w", encoding="utf-8-sig", newline="") as target:
        writer = csv.DictWriter(target, fieldnames=fieldnames)
        writer.writeheader()
        for row in passed_rows:
            signal_date = str(row.get("signal_date") or "")
            day_feature = post_filter_day_features.get(signal_date) or {}
            if "post_filter_min_count" in variant and int(day_feature.get("count") or 0) < int(variant["post_filter_min_count"]):
                continue
            if "post_filter_min_primary_count" in variant and int(day_feature.get("primary_count") or 0) < int(variant["post_filter_min_primary_count"]):
                continue
            if "post_filter_avg_pred_min" in variant:
                avg_pred = _to_float(day_feature.get("avg_pred"))
                if avg_pred is None or avg_pred < float(variant["post_filter_avg_pred_min"]):
                    continue
            row = dict(row)
            rank = int(float(row.get("rank") or 0))
            rank_targets = variant.get("rank_target_pct") or {}
            target_pct = rank_targets.get(rank, variant["target_pct"])
            row["target_pct"] = f"{float(target_pct):.5f}"
            row["holding_days"] = str(int(variant["holding_days"]))
            row["score_exit_entry_ratio"] = str(variant.get("score_exit_entry_ratio", "1.0"))
            row["min_holding_days_before_score_exit"] = str(variant.get("min_holding_days_before_score_exit", "3"))
            writer.writerow(row)


def _extract_indicator(log_file: Path) -> dict | None:
    if not log_file.exists():
        return None
    for line in reversed(log_file.read_text(encoding="utf-8", errors="ignore").splitlines()):
        if "GM_BACKTEST_INDICATOR:" not in line:
            continue
        payload = line.split("GM_BACKTEST_INDICATOR:", 1)[1].strip()
        try:
            return ast.literal_eval(payload)
        except Exception:
            return eval(payload, {"__builtins__": {}}, {"datetime": datetime_module})
    return None


def _exposure_stats(log_file: Path) -> dict:
    values = []
    active = []
    pattern = re.compile(r"EXPOSURE .* invested_pct=([0-9.]+).*active_positions=(\d+)")
    if not log_file.exists():
        return {"avg_invested_pct": None, "ge80_ratio": None, "max_active_positions": None, "exposure_points": 0}
    for match in pattern.finditer(log_file.read_text(encoding="utf-8", errors="ignore")):
        values.append(float(match.group(1)))
        active.append(int(match.group(2)))
    if not values:
        return {"avg_invested_pct": None, "ge80_ratio": None, "max_active_positions": None, "exposure_points": 0}
    return {
        "avg_invested_pct": sum(values) / len(values),
        "ge80_ratio": sum(1 for value in values if value >= 0.80) / len(values),
        "max_active_positions": max(active) if active else None,
        "exposure_points": len(values),
    }


def _signal_stats(signal_file: Path) -> dict:
    with signal_file.open("r", encoding="utf-8-sig", newline="") as file:
        rows = list(csv.DictReader(file))
    targets = [_to_float(row.get("target_pct")) for row in rows]
    targets = [value for value in targets if value is not None]
    return {
        "signal_count": len(rows),
        "buy_days": len({row.get("buy_date") for row in rows if row.get("buy_date")}),
        "avg_signal_target_pct": sum(targets) / len(targets) if targets else None,
        "max_signal_target_pct": max(targets) if targets else None,
        "min_signal_target_pct": min(targets) if targets else None,
    }


